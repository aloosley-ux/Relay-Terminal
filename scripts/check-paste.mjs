import { chromium } from 'playwright';
const b=await chromium.connectOverCDP('http://127.0.0.1:9225');
const p=b.contexts()[0].pages()[0];
if(await p.getByRole('button',{name:'Close terminal search',exact:true}).count()) await p.getByRole('button',{name:'Close terminal search',exact:true}).click();
console.log('set',await p.evaluate(()=>window.__TAURI_INTERNALS__.invoke('clipboard_write',{text:'Write-Output "PASTE_REAL_café_λ"'})));
console.log('read',await p.evaluate(()=>window.__TAURI_INTERNALS__.invoke('clipboard_read')));
await p.getByRole('button',{name:'Paste · Ctrl+Shift+V',exact:true}).click();
await p.waitForTimeout(300);
console.log('after paste',await p.locator('.terminal-host:visible').innerText());
console.log('toast',await p.locator('.toast').innerText({timeout:100}).catch(()=>''));
await p.locator('.terminal-host:visible textarea').focus();
await p.keyboard.press('Enter');
await p.waitForTimeout(300);
console.log('after enter',await p.locator('.terminal-host:visible').innerText());
await p.evaluate(()=>window.__TAURI_INTERNALS__.invoke('clipboard_write',{text:'Write-Output "SHORTCUT_PASTE"'}));
await p.locator('.terminal-host:visible textarea').focus();
await p.keyboard.press('Control+Shift+v');
await p.waitForTimeout(300);
console.log('after shortcut',await p.locator('.terminal-host:visible').innerText());
await p.keyboard.press('Enter');
await p.waitForTimeout(300);
console.log('after shortcut enter',await p.locator('.terminal-host:visible').innerText());
await b.close();
