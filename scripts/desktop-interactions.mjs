import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.connectOverCDP(`http://127.0.0.1:${process.argv[2] || 9225}`);
const page=browser.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('tauri.localhost'));
if(!page)throw new Error('A native Relay test window is required');
page.setDefaultTimeout(15000);
const results=[],errors=[];
page.on('pageerror',e=>errors.push(e.message));
const log=name=>{results.push({name,pass:true});console.log('PASS '+name);};
const ready=()=>page.locator('.statusbar').getByText('Ready',{exact:true}).waitFor();
const native=(name,args={})=>page.evaluate(({name,args})=>window.__TAURI_INTERNALS__.invoke(name,args),{name,args});
await page.getByRole('button',{name:'Terminal view',exact:true}).click();await ready();
assert.equal(await page.getByRole('tab').count(),1);
await page.getByRole('button',{name:'Split terminal',exact:true}).click();
await page.waitForFunction(()=>document.querySelectorAll('[role=tab]').length===2);
await ready();assert.equal(await page.locator('.terminal-host:visible').count(),2);
log('Split from one tab creates a real second shell');
const left=await page.locator('.terminal-host.pane-left').getAttribute('data-session');
const right=await page.locator('.terminal-host.pane-right').getAttribute('data-session');
await page.locator('.terminal-host.pane-left').click({position:{x:40,y:35}});
assert.equal(await page.locator('.terminal-host.pane-left').getAttribute('data-session'),left);
assert.equal(await page.locator('.terminal-host.pane-right').getAttribute('data-session'),right);
await page.keyboard.press('Alt+ArrowRight');
await page.waitForFunction(key=>document.querySelector('.pane-active')?.getAttribute('data-session')===key,right);
assert.equal(await page.locator('.pane-left').getAttribute('data-session'),left);
log('Pointer and Alt+arrow focus keep pane positions stable');
await page.getByRole('separator',{name:'Resize terminal panes',exact:true}).focus();
await page.keyboard.press('ArrowLeft');await page.keyboard.press('ArrowLeft');
assert.equal(await page.getByRole('separator',{name:'Resize terminal panes'}).getAttribute('aria-valuenow'),'40');
await page.waitForTimeout(120);
const widths=await page.locator('.terminal-host:visible').evaluateAll(els=>els.map(el=>el.getBoundingClientRect().width));
assert(widths[1]>widths[0]);
log('Split resizing is available from the keyboard');
await page.getByRole('button',{name:'Close split view',exact:true}).click();
await page.getByRole('tab').first().focus();await page.keyboard.press('ArrowRight');await page.waitForTimeout(100);
assert.equal(await page.getByRole('tab',{selected:true}).getAttribute('tabindex'),'0');
assert.equal(await page.evaluate(()=>document.activeElement?.getAttribute('role')),'tab');
log('Arrow-key tab navigation keeps keyboard focus on the tab strip');
await page.keyboard.press('Control+Shift+p');
await page.getByLabel('Search commands',{exact:true}).fill('');
await page.keyboard.press('End');
for(let i=0;i<22;i++)await page.keyboard.press('ArrowDown');
assert(await page.locator('.palette-results .selected').evaluate(e=>{const r=e.getBoundingClientRect(),p=e.parentElement.getBoundingClientRect();return r.top>=p.top-1&&r.bottom<=p.bottom+1;}));
await page.keyboard.press('Escape');log('Palette keyboard selection scrolls into view');
await page.getByRole('button',{name:'Projects view',exact:true}).click();
await page.locator('.project-index').waitFor();
assert.equal(await page.locator('.navigator .project-index').count(),1);
assert.equal(await page.locator('.workbench .project-index').count(),0);
log('Project folders use the shared navigator');
await page.getByRole('button',{name:'Processes view',exact:true}).click();
assert.equal(await page.locator('.process-inspector:visible').count(),0);
log('Empty process inspector does not reserve workspace width');
await page.getByRole('button',{name:'Files view',exact:true}).click();
assert.equal(await page.locator('.file-preview:visible').count(),0);
log('Empty file preview does not reserve workspace width');
await page.getByRole('button',{name:'Terminal view',exact:true}).click();
await page.keyboard.press('Control+Shift+b');
assert.equal(await page.locator('.navigator').evaluate(e=>Math.round(e.getBoundingClientRect().width)),52);
assert.equal(await page.getByRole('button',{name:'Projects view',exact:true}).count(),1);
await page.keyboard.press('Control+Shift+b');log('Collapsed navigator keeps every view accessible');
await page.emulateMedia({reducedMotion:'reduce'});
await page.keyboard.press('Control+,');
assert.equal(await page.locator('.modal').evaluate(e=>getComputedStyle(e).animationName),'none');
await page.keyboard.press('Escape');
log('Reduced motion removes dialog animation');
for(const theme of ['Dark','Light']) {
  await page.keyboard.press('Control+,');await page.getByRole('button',{name:theme,exact:true}).click();await page.getByRole('button',{name:'Done',exact:true}).click();
  for(const size of [{width:760,height:500},{width:1000,height:700},{width:1400,height:880}]) {
    await native('plugin:window|set_size',{label:'main',value:{Logical:size}});await page.waitForTimeout(150);
    for(const view of ['Terminal','Projects','Processes','Files']) {
      await page.getByRole('button',{name:view+' view',exact:true}).click();
      const overflow=await page.locator('.workspace-content').evaluate(e=>e.scrollWidth>e.clientWidth+1);
      assert(!overflow,`${theme} ${view} ${size.width}: horizontal overflow`);
      assert(await page.locator('.app').evaluate(e=>e.scrollTop===0),`${theme} ${view}: root scrolled out of place`);
      const vertical=await page.evaluate(()=>{const work=document.querySelector('.workspace-content').getBoundingClientRect(),footer=document.querySelector('.statusbar').getBoundingClientRect(),main=document.querySelector('.terminal-main');return work.bottom<=footer.top+1&&(getComputedStyle(main).display==='none'||main.getBoundingClientRect().bottom<=work.bottom+1);});
      assert(vertical,`${theme} ${view} ${size.width}: content covers status bar`);
      const sidebar=await page.locator('.navigator').evaluate(e=>({width:e.clientWidth,scroll:e.scrollWidth}));
      assert(sidebar.scroll<=sidebar.width+1,`${theme} sidebar horizontal overflow`);
    }
  }
  log(`${theme} layout fits all four views at 760, 1000 and 1400 pixels`);
}
await page.keyboard.press('Control+,');await page.getByRole('button',{name:'Dark',exact:true}).click();await page.getByRole('button',{name:'Done',exact:true}).click();
await page.getByRole('button',{name:'Terminal view',exact:true}).click();
assert.deepEqual(errors,[]);
await fs.writeFile('artifacts/desktop-interaction-results.json',JSON.stringify({results,errors},null,2));
await browser.close();
