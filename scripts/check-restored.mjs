import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const b=await chromium.connectOverCDP('http://127.0.0.1:9225');
const p=b.contexts()[0].pages().find(p=>p.url().includes('tauri.localhost'));
p.setDefaultTimeout(15000);
await p.locator('.statusbar[data-status="ready"]').waitFor();
await p.getByRole('button',{name:'Settings · Ctrl+,',exact:true}).click();
assert.equal(await p.getByRole('button',{name:'Dark',exact:true}).getAttribute('class'),'selected');
await p.getByRole('button',{name:'Done',exact:true}).click();
await p.getByRole('button',{name:'Actions',exact:true}).click();
await p.getByText('Fixture check',{exact:true}).waitFor();
await p.getByRole('button',{name:'Unfavourite Fixture check',exact:true}).waitFor();
await p.getByText('Edited and persisted',{exact:true}).waitFor();
assert.equal(await p.getByRole('tab').count(),3);
await p.getByRole('button',{name:'Workspaces',exact:true}).click();
await p.locator('.workspace-open').filter({hasText:'Relay test workspace'}).waitFor();
await p.locator('.directory-row').filter({hasText:'Nostalgia'}).waitFor();
await p.getByRole('tab',{name:'PowerShell',exact:true}).click();
await p.waitForTimeout(80);
await p.getByLabel('Command input',{exact:true}).fill('Write-Output ("FRESH_STATE=" + [bool](Get-Variable relayState -ErrorAction SilentlyContinue))');
await p.locator('.command-bar').getByRole('button',{name:'Run',exact:true}).click();
await p.waitForFunction(()=>document.querySelector('.terminal-host')?.textContent.includes('FRESH_STATE=False'));
await p.locator('.statusbar[data-status="ready"]').waitFor();
await fs.writeFile('artifacts/restart-test.json',JSON.stringify({passed:true,restored:['theme','favourites','edited saved action','favourite action','workspace','three tab names and directories'],shellState:'Fresh process: previous variables do not survive app restart'},null,2));
console.log('PASS restart: theme, actions, favourites, workspaces and three tab directories restored; fresh shell state confirmed.');
await b.close();
