import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const browser = await chromium.connectOverCDP(`http://127.0.0.1:${process.argv[2] || process.env.RELAY_TEST_PORT || 9225}`);
const page = browser.contexts().flatMap(c => c.pages()).find(p => p.url().includes('tauri.localhost'));
if (!page) throw new Error('The native Relay test window is required');
page.setDefaultTimeout(15000);
const directory = process.env.RELAY_SCREENSHOTS || 'artifacts/desktop-review';
await fs.mkdir(directory, { recursive:true });
const shot=async name=>{await page.waitForTimeout(180);await page.screenshot({path:`${directory}/${name}.png`}); console.log(name, await page.evaluate(()=>({width:innerWidth,height:innerHeight})));};
if (await page.getByRole('dialog').count()) await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Terminal view',exact:true}).click();
await page.locator('.statusbar').getByText('Ready',{exact:true}).waitFor();
await shot('terminal-dark');
await page.getByRole('button',{name:'Projects view',exact:true}).click();
await page.getByRole('button',{name:'Use terminal’s current folder',exact:true}).click();
await page.locator('.project-task').first().waitFor();
await shot('projects-dark');
await page.getByRole('button',{name:'Processes view',exact:true}).click();
await page.getByRole('button',{name:'Refresh',exact:true}).waitFor();
await page.waitForFunction(()=>document.querySelector('.refresh-time')?.textContent.startsWith('Checked'),{},{timeout:60000});
await shot('processes-dark');
await page.getByRole('button',{name:'Files view',exact:true}).click();
await page.getByRole('button',{name:'Current terminal',exact:true}).click();
await page.locator('.file-entries').getByRole('button',{name:/package.json/}).click();
await page.locator('.file-preview pre').waitFor();
await shot('files-dark');
await page.getByRole('button',{name:'Terminal view',exact:true}).click();
await page.keyboard.press('Control+,');
await shot('settings-dark');
await page.getByRole('button',{name:'Light',exact:true}).click();
await page.getByRole('button',{name:'Done',exact:true}).click();
await shot('terminal-light');
await page.getByRole('button',{name:'Projects view',exact:true}).click();
await shot('projects-light');
await page.keyboard.press('Control+,');
await page.getByRole('button',{name:'Dark',exact:true}).click();
await page.getByRole('button',{name:'Done',exact:true}).click();
await page.getByRole('button',{name:'Terminal view',exact:true}).click();
await browser.close();
