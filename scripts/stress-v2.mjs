import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { performance } from 'node:perf_hooks';
const browser = await chromium.connectOverCDP('http://127.0.0.1:9225');
const page = browser.contexts()[0].pages().find(p=>p.url().includes('tauri.localhost'));
page.setDefaultTimeout(20000);
const ready = () => page.locator('.statusbar').getByText('Ready',{exact:true}).waitFor();
await page.getByRole('button',{name:'Terminal view',exact:true}).click();
await ready();
if(await page.getByRole('button',{name:'Close split view',exact:true}).count()) await page.getByRole('button',{name:'Close split view',exact:true}).click();
const before = await page.locator('.status-dimensions').innerText();
await page.getByLabel('Command input',{exact:true}).fill('1..1000000 | ForEach-Object { "FLOOD_$($_) café λ 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ" }');
await page.locator('.command-bar').getByRole('button',{name:'Run',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('.terminal-host.pane-active')?.textContent.includes('FLOOD_'));
await page.waitForTimeout(150);
const navigationStart = performance.now();
await page.getByRole('button',{name:'Processes view',exact:true}).click();
await page.getByRole('heading',{name:'Processes',exact:true}).waitFor();
const navigationMs = Math.round(performance.now()-navigationStart);
assert.equal(await page.locator('.status-dimensions').innerText(), before, 'Hidden PTY dimensions must not shrink');
const interruptStart = performance.now();
await page.locator('.statusbar').getByRole('button',{name:/Interrupt/}).click();
await ready();
const interruptMs = Math.round(performance.now()-interruptStart);
assert(navigationMs < 1500); assert(interruptMs < 10000);
await page.getByRole('button',{name:'Terminal view',exact:true}).click(); await page.waitForTimeout(100);
const tabStart = performance.now();
await page.getByRole('tab').first().click(); await ready();
const switchMs = Math.round(performance.now()-tabStart);
const result={navigationDuringFloodMs:navigationMs,interruptToReadyMs:interruptMs,tabSwitchMs:switchMs,hiddenPtyDimensionsPreserved:true,method:'Real PowerShell one-million-line pipeline interrupted through GUI during acknowledged PTY output. On-demand service discovery may overlap.'};
await fs.writeFile('artifacts/v2-stress-metrics.json',JSON.stringify(result,null,2)); console.log(result);
await browser.close();
